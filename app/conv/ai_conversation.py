# お金・貯金そのものを指す語。これ単独でもお金の話題とみなす（誤爆の少ない明確な語だけ）。
# 明確なお金語。これ単独でお金の話題とみなしてよい（食べ物・遊びの雑談には出ない語だけ）。
# 「円」は数量にも付くため（100円のパン等）ここには入れない。下で購買動詞との共起を要求する。
_COACHING_MONEY_WORDS = (
    "お金", "おかね", "おこづかい", "お小遣い", "貯金", "ちょきん", "査定", "入金", "支給",
)
# 金銭移動が明示された高信頼の動詞。これ単独でお金の話題とみなす（「パンかった」「おかし買った」など
# 金額語も『円』も無い最頻出の実支出発話を、学習支援の中心なのに取りこぼしていた過剰抑制を直す）。
# 「たべた」等の食事動詞は入れない（食べ物雑談を拾わないため）。「かった」は「たのしかった」を拾うため
# 使わず、購買を表す「買っ」（漢字）に限定する。
_COACHING_STRONG_ACTION_WORDS = (
    "買っ", "かいもの", "もらった", "ためた", "貯め", "ためる", "目標", "もくひょう",
    "払っ", "はらっ", "受け取っ", "うけとっ",
)
# 金銭以外にも使う曖昧な動詞（時間・体力にも「つかった」）。お金の文脈（お金語 or 金額）との共起を要求する。
_COACHING_WEAK_ACTION_WORDS = (
    "つかった", "使っ",
)
# 単なる残高・履歴の照会。これだけの発話ではコーチングを出さない（お金の話でも問いかけは邪魔）。
_COACHING_SUPPRESS_ONLY = ("残高", "ざんだか", "いくらある", "履歴", "りれき", "台帳")

def _has_amount_expr(text: str) -> bool:
    """金額表現（数字＋円）を含むか。個数・時刻の裸の数字は金額とみなさない。

    「100円」は金額だが「3匹」「5分」「あと5個」は金額ではない。数字に『円』が隣接する
    ときだけ金額文脈とみなし、コーチングの誤爆（個数・時刻の数字での発火）を防ぐ。
    """
    import re as _re
    # 半角/全角数字の直後に（空白を挟んでも）『円』が続くパターンだけを金額とみなす
    return bool(_re.search(r"[0-9０-９]+\s*円", text))


def _is_money_topic(text: str) -> bool:
    """発話がお金の話題か。コーチング出し分けの中核判定（誤爆と過剰抑制の両方を避ける）。

    お金の話題とみなす条件（いずれか）:
      (1) 明確なお金語（お金・貯金・査定・入金・支給等）を含む。
      (2) 高信頼の金銭移動動詞（買っ・もらった・ためた・目標等）を含む＝金額が無くても実支出/入金/貯金。
      (3) 金額表現（数字＋円）と曖昧動詞（つかった・使っ）が共起する（例「300円つかった」）。
    「ポケモンほしい」「すいかたべた」「100円のパンたべたい」は発火しない（願望・食事雑談を拾わない）。
    """
    has_money_word = any(w in text for w in _COACHING_MONEY_WORDS)
    has_strong = any(w in text for w in _COACHING_STRONG_ACTION_WORDS)
    has_amount = _has_amount_expr(text)
    has_weak = any(w in text for w in _COACHING_WEAK_ACTION_WORDS)
    return has_money_word or has_strong or (has_amount and has_weak)


# 完了した取引を表す動詞パターン（正規表現）。丁寧形・言い換えも拾う。過去・完了の断定に限る。
# 「買った/買いました」「使った/使いました」「もらった/もらいました/受け取った」「払った/払いました」。
# 「少なかった・楽しかった・うれしかった」等の形容詞過去に誤マッチしないよう、購買動詞は語幹を固定する。
import re as _re_txn
_CONFIRMED_TXN_RE = _re_txn.compile(
    r"(買っ(た|ちゃった)|買いました|つかった|使った|使いました|つかいました|"
    r"もらった|もらいました|受け取った|払った|払いました|はらった)"
)
# 相談・迷い・振り返り・計画・継続を示す語。1つでもあれば「純粋な確定記録」ではない（コーチング対象）。
# 語彙で全列挙はできないため、確定取引の“骨格以外の節”の存在を示す接続語・評価語・意志表現を広めに拾う。
_NON_PURE_RECORD_MARKERS = (
    # 相談・迷い・欲求
    "ほしい", "欲しい", "どうしよう", "どうすれば", "どう思う", "いいかな", "かな", "いい？", "迷", "まよ",
    "買いたい", "かいたい", "貯めたい", "ためたい", "増やして", "ふやして", "相談",
    "よさそう", "何に", "なにに", "どうしたら", "どっち",
    # 計画・意志・継続（未来）
    "ためる", "貯め", "貯金", "目標", "つもり", "ことにした", "しようと", "したい", "これから", "次から", "つぎから", "毎週", "毎月",
    # 振り返り・評価（買った事実に感想が付く＝観察の入口）
    "後悔", "無駄", "むだ", "高かった", "安かった", "買いすぎ", "つかいすぎ", "使いすぎ", "よかった", "どうだった",
    "失敗", "しっぱい", "覚えてない", "おぼえてない", "使い道", "つかいみち", "使おう", "つかおう",
    # 仮定・条件（まだ起きていない＝確定記録ではない）
    "たら", "れば", "場合", "ばあい", "としたら", "だったら", "どうなる", "どうしよう",
    # 節の接続（取引以外の節が続く合図）
    "けど", "けれど", "から", "ので", "し、", "でも",
)


def _is_pure_confirmed_transaction(text: str) -> bool:
    """発話が「完了済みの支出/入金だけ」の単純な記録か判定する（相談・計画・振り返りを含まない）。

    確定取引は記録が最優先で観察の問いを挟まない（codex #3）ため、このときだけコーチングを外す。
    完了取引の動詞（丁寧形・言い換え含む）を含み、かつ相談・計画・振り返り・別の節を示す語や疑問符を
    一切含まない“純粋な記録”のときだけ True。少しでも観察の入口があれば False（過剰抑制を防ぐ・codex #1）。
    """
    t = text or ""
    # 完了取引の動詞が無ければ確定記録ではない（正規表現で形容詞過去への誤マッチを避ける）
    if not _CONFIRMED_TXN_RE.search(t):
        return False
    # 相談・計画・振り返り・別の節・疑問符が1つでもあれば純粋な記録ではない
    if any(w in t for w in _NON_PURE_RECORD_MARKERS) or ("？" in t) or ("?" in t):
        return False
    return True


def _should_coach(input_text: str) -> bool:
    """この発話でコーチングを付けるべきか判定する。お金・貯金の話題のときだけ True。

    _is_money_topic でお金の話題を判定し、単なる残高・履歴照会「だけ」の発話では出さない
    （お金の話でも問いかけは監視的で邪魔なため）。さらに、純粋な確定記録（『300円つかった』等で
    相談・計画・振り返りを含まない）でもコーチングを出さない（確定取引は記録が最優先・codex #3）。
    計画・目標・振り返り・複合相談はコーチング対象に残す（codex 実装レビュー #1 の過剰抑制修正）。
    """
    text = input_text or ""
    if not _is_money_topic(text):
        return False
    # 残高・履歴の照会「だけ」ならコーチングを出さない
    stripped = text
    for w in _COACHING_SUPPRESS_ONLY:
        stripped = stripped.replace(w, "")
    if not _is_money_topic(stripped):
        return False
    # 純粋な確定記録だけを除外する（計画・振り返り・相談は残す）
    if _is_pure_confirmed_transaction(text):
        return False
    # コーチングに値する要素があるときだけ出す。単なる状態のつぶやき（例「お小遣いが少なかった」＝
    # 取引でも相談でも計画でもない）は監視的になるため出さない（codex 実装レビュー2周目 #1）。
    has_purchase_action = any(w in text for w in _COACHING_STRONG_ACTION_WORDS) or any(w in text for w in _COACHING_WEAK_ACTION_WORDS)
    has_consult_or_plan = any(w in text for w in _NON_PURE_RECORD_MARKERS) or ("？" in text) or ("?" in text)
    return has_purchase_action or has_consult_or_plan


async def _build_coaching_block_async(user_conf: dict, input_text: str) -> str:
    """お金・学習の話題のターンだけ、その子の learning_insights をコーチング指示へ整形する。

    出し分け（_should_coach）と反復抑制（直近同一 child_action は出さない）を行い、build_learning_insights
    の同期 I/O は asyncio.to_thread でオフロードしてイベントループをブロックしない。子どもには分析や親メモを
    そのまま見せず、child_action を1つさりげなく促す。叱責しない。取得失敗時は空文字。

    Args:
        user_conf: 対象児童の設定 dict。
        input_text: 今回の子どもの発話（出し分け判定に使う）。

    Returns:
        str: system prompt へ足すコーチング指示。出さない場合は空文字。
    """
    # 出し分け: お金・学習の話題でなければコーチングなし
    if not _should_coach(input_text):
        return ""
    user_name = str(user_conf.get("name", ""))
    try:
        # 同期 I/O（90日ログ読取）をスレッドへ逃がしイベントループを止めない
        insights = await asyncio.to_thread(deps.learning_insights, user_conf)
    except Exception:
        # インサイト計算の失敗で会話を止めない。コーチングなしで通常会話にフォールバック
        return ""
    challenge = insights.get("child_challenge") or {}
    challenge_action = str(challenge.get("action") or "").strip()
    cards = insights.get("insight_cards") or []
    top = cards[0] if cards else {}
    skill = str(top.get("skill") or "").strip()
    child_action = str(top.get("child_action") or challenge_action).strip()
    if not child_action:
        return ""
    # 反復抑制: 直近同じ child_action を会話コーチングで促していたら今回は促さない（くどさ・監視感を避ける）。
    # プロセス内 dict でなく learning_support_state の last_coaching_at/action（永続・時間ベース）で判定し、
    # 再起動で抑制が消える／プロセス寿命に抑制期間が依存する両極端を避ける。取得失敗時は抑制なしで出す。
    try:
        recent_action = await asyncio.to_thread(deps.recent_coaching_action, user_conf)
    except Exception:
        recent_action = ""
    if recent_action and recent_action == child_action:
        return ""
    # learning_support_state へ会話専用キーで書き戻し、再起動を跨いだ反復抑制・3日 type dedup を会話経路にも
    # 効かせる（best-effort、失敗は握る）。challenge_stale の時計は触らない。card_type は insight_card の type
    card_type = str(top.get("type") or "").strip()
    try:
        # save_coaching_nudge は flock(LOCK_EX ブロッキング)+ファイル RMW を行う。親の Web 保存や
        # reminder cron が同じ .json.lock を保持中だと、生呼びでは Discord のイベントループ全体
        # (全児童の会話・考え中表示・heartbeat)がブロックする。同関数内の他3依存と同様 to_thread へ逃がす。
        await asyncio.to_thread(deps.save_coaching_nudge, user_conf, card_type, child_action)
    except Exception:
        pass
    return (
        "\n【学習支援の候補（命令ではない。上の『まず観察する』の後で、噛み合うときだけ使う）】\n"
        f"- この子に促せそうな小さな行動の“候補”は「{child_action}」"
        + (f"（伸ばしたい力: {skill}）" if skill else "")
        + "。ただし必須ではない。観察の結論とこの候補が噛み合うときだけ、一度に1つそっと添える。噛み合わなければ使わない。\n"
        "- 使うときも「がんばろうね」で終わらせず、①今どうなっているか一言そえて、②5分でできる小さな行動を1つだけ、"
        "押しつけずに提案する。\n"
        "- 上の分析や親向けメモはそのまま読み上げない。子どもが自分で選べる形（今買う/待つ/別にする 等）にする。\n"
        "- この小さな行動は、今回の発話内容に自然につながる場合だけそっと触れる。無関係な話題（例: 入金の報告なのに"
        "支出を減らす話）には無理に絡めず、その時は素直に受け止める方を優先する。\n"
        "- 叱ったり、できていない点を並べたりしない。一度に出す提案は1つだけにする。"
    )


# 能動ナッジへの返事とみなせる短い反応語。これらか、お金話題のときだけ「チャレンジに返答した」とみなす。
# 肯定・保留・否定・完了/未完了の報告を広めに拾う。no_record への「なにもかってない」、challenge への
# 「やってない/わからない」等の自然な返事も、直前の問いかけと噛み合わせるため反応語に含める(codex ux)。
_NUDGE_REPLY_WORDS = (
    "やった", "できた", "やってみた", "あとで", "まだ", "これから", "ちがう", "ちがった",
    "むり", "できなかった", "わすれた", "うん", "はい", "いいえ", "ううん",
    "かってない", "買ってない", "してない", "やってない", "わからない", "わかんない",
    "おわった", "終わった", "かたづけた", "そうじした", "おぼえてない", "覚えてない",
)


# チャレンジを「合わない・やめたい」と断る返事語。これが来たらそのチャレンジは終了扱いにし、
# 数日後に蒸し返さない（codex ux: 「ちがう」と返したチャレンジをまた聞かれる問題）。
_NUDGE_DECLINE_WORDS = (
    "ちがう", "ちがった", "むり", "やらない", "やりたくない", "いや", "しない", "やめる", "やめたい",
)


def _looks_like_nudge_reply(input_text: str) -> bool:
    """今回の発話が、直前の能動ナッジ（チャレンジ）への返事とみなせるか。

    反応語（やった/あとで/ちがう/まだ 等）を含むか、お金の話題（_is_money_topic）ならば返事とみなす。
    無関係な雑談（おはよう・みかん食べた等）では False にし、challenge_stale の誤抑制を防ぐ。
    """
    text = (input_text or "").strip()
    if not text:
        return False
    if any(w in text for w in _NUDGE_REPLY_WORDS):
        return True
    return _is_money_topic(text)


def _looks_like_decline(input_text: str) -> bool:
    """今回の返事が「そのチャレンジは合わない・やめたい」と断る内容か。

    これが True の返事でチャレンジに応じたときは、そのチャレンジを終了扱い（feedback=declined）にして
    数日後の蒸し返しを止める。肯定語（やった/できた）が同時にあれば断りとみなさない（前向きを優先）。
    """
    text = (input_text or "").strip()
    if not text:
        return False
    # 前向きな完了語があれば断りにしない
    if any(w in text for w in ("やった", "できた", "やってみた", "おわった", "終わった")):
        return False
    return any(w in text for w in _NUDGE_DECLINE_WORDS)


async def _build_nudge_bridge_block_async(user_conf: dict, input_text: str) -> str:
    """未消費の能動伴走ナッジがあれば、system prompt へ「前回きみに聞いたこと」を1回だけ注入する。

    reminder が channel.send で直接送った問いかけは claude セッションに載らないため、次に子が
    「やった/あとで/ちがう」と短く返しても claude はその問いかけを送った記憶が無く、伴走が会話
    として噛み合わない。deps.take_pending_nudge_bridge で橋渡し本文を取り出し（取り出したら消費）、
    直前に自分が投げかけた文脈として claude に持たせる。お金・学習の話題判定（_should_coach）とは
    独立に効かせる（返答『やった』等はお金語を含まないため）。

    child_response（challenge_stale の抑制材料）を書くのは、今回の発話が返事とみなせるとき
    （_looks_like_nudge_reply）だけに限定する。無関係な雑談1回で別チャレンジの challenge_stale が
    誤抑制されるのを防ぐ。橋渡し本文の会話注入自体は返事かどうかに関わらず毎回行う（文脈を繋ぐため）。

    Args:
        user_conf: 対象児童の設定 dict。
        input_text: 今回の子どもの発話（返事らしさの判定に使う）。

    Returns:
        str: system prompt へ足す橋渡し指示。無ければ空文字。
    """
    is_reply = _looks_like_nudge_reply(input_text)
    # 「ちがう/やめたい」等の断りなら declined として記録し、そのチャレンジを終了扱いにする(蒸し返し防止)
    declined = is_reply and _looks_like_decline(input_text)
    try:
        # 状態ファイル I/O をスレッドへ逃がしイベントループを止めない。返事とみなせるときだけ
        # child_response を書かせる（record_response=is_reply）。declined なら feedback を declined に。
        bridge_text = await asyncio.to_thread(deps.take_pending_nudge_bridge, user_conf, is_reply, declined)
    except Exception:
        # 橋渡し取得の失敗で会話を止めない
        return ""
    bridge_text = (bridge_text or "").strip()
    if not bridge_text:
        return ""
    # 改行はプロンプト内で1行に畳む（system prompt の可読性のため）
    one_line = " ".join(bridge_text.split())
    return (
        "\n【前回きみから声をかけた続き（意識する）】\n"
        f"- 少し前にきみからこの子へ《{one_line}》と声をかけたよ。\n"
        "- 今回の発話がその返事（例: やった／あとで／ちがう／まだ）なら、その文脈を踏まえて自然に受け止めること。\n"
        "- 関係ない話題なら、この声かけには触れず、今の話にふつうに応じること。しつこく蒸し返さない。"
    )


def _parse_output(stdout_text: str) -> tuple[bool, str, str | None]:
    """claude CLI の JSON 出力を解釈し、(成功したか, 応答文, session_id) を返す。

    --output-format json は最終結果を1つの JSON オブジェクトで返す。is_error が真、または
    JSON として解釈できない出力は失敗とみなす。呼び出し側は成功時のみ result を応答として使う。

    Args:
        stdout_text: claude CLI の標準出力全体。

    Returns:
        tuple[bool, str, str | None]: (成功, 応答文, session_id)。失敗時は (False, "", session_id or None)。
    """
    text = stdout_text.strip()
    if not text:
        return False, "", None
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        # JSON でなければ失敗扱い。エラー文を子どもへ流さない
        return False, "", None
    if not isinstance(data, dict):
        return False, "", None
    session_id = data.get("session_id")
    session_id = str(session_id) if session_id else None
    # is_error が真なら CLI はエラーを返している。result はエラー文なので応答に使わない
    if data.get("is_error"):
        return False, "", session_id
    result = str(data.get("result") or "")
    if not result:
        return False, "", session_id
    # 思考混入の検知のみ行い、応答は一切加工しない（2026/08/09 方針転換）。
    # 旧実装は正規表現で思考を除去していたが、(1)実機の漏れ方（先頭が日本語）を検出できず素通りさせ、
    # (2)除去の結果 result が空になると失敗扱いになり「もう一度話しかけて」を連発する二次被害を出した。
    # 原因は CLI 2.1.179 の既知バグ（thinking が text ブロックへ混入）であり 2.1.226 で解消を確認したため、
    # 出口での加工をやめ、再発を即座に把握するための検知だけを残す。弾かない・切らない・失敗にしない。
    _detect_thinking_leak(result)
    return True, result, session_id


# 思考混入の目印。実機で漏れた11件は全て「th + 大文字始まりの英文」という完全に一致した規則を持つ
# （生データを1文字ずつ検証済み。th は純粋な ASCII でありタグの残骸ではない）。
_THINKING_LEAK_TH_RE = re.compile(r"^th[A-Z]")
# 英文が2語以上つづく形。思考は英語で走るため、応答冒頭に英文が連続するのは混入の兆候
_THINKING_LEAK_ENG_RE = re.compile(r"[A-Za-z][A-Za-z',\-]+\s+[A-Za-z]{2,}")


def _detect_thinking_leak(text: str) -> bool:
    """応答に思考が混入していないか検知し、見つけたら診断ログへ記録する（応答は加工しない）。

    子に内部の判断過程が見えると、対等に観察するというコーチングの芯（docs/コーチング.md）が崩れる。
    ただし出口で除去する方式は、実機の漏れ方を検出できず素通りさせた一方、除去が効きすぎると
    本文が空になり会話を止めるという二次被害を出した。よって「弾かず・切らず・失敗にせず、記録だけする」。
    検知が出たら CLI/モデルの更新で再発した合図であり、環境側で対処する。

    Args:
        text: claude が返した応答文（加工前）。

    Returns:
        bool: 思考混入を検知したら True（呼び出し側は応答をそのまま使ってよい）。
    """
    head = text.lstrip()[:200]
    mark = ""
    if _THINKING_LEAK_TH_RE.match(head):
        mark = "th_prefix"
    elif len(_THINKING_LEAK_ENG_RE.findall(head)) >= 2:
        # 冒頭200文字に英文が2つ以上。日本語会話では通常起きない
        mark = "english_reasoning"
    if not mark:
        return False
    # 応答そのものは子に届く。ここで止めると会話が壊れるため、記録に徹する
    _diag("thinking_leak_detected", {"mark": mark, "head": head[:150]})
    return True


class _ProcessNeverStarted(Exception):
    """claude プロセスの起動(create_subprocess_exec)自体に失敗したことを表す専用例外。

    この例外に限り「tool は1つも実行されていない」と確証できるため、呼び出し側は再入力を促してよい。
    プロセスが立った後の通信例外・タイムアウトは tool 実行済みの可能性があるため、この例外にはしない
    （その場合は二重課金を避けるため再入力を促さない）。codex 指摘: 起動と通信を1関数で扱い全例外を
    「tool未実行」と誤分類すると、communicate 後の例外や resume 再試行のタイムアウトで二重課金する。
    """


async def _spawn_claude(prompt: str, session_id: str | None, system_prompt: str, child_name: str,
                        parent_mode: bool = False, disable_tools: bool = False,
                        fork_session: bool = False, new_session_id: str | None = None):
    """claude CLI を subprocess 起動して (returncode, stdout, stderr) を返す。失敗時は例外。

    子どもの発話は `--` セパレータの後の位置引数として渡す。`-p <発話>` 方式だと、`--` で
    始まる発話（例「--help」「--model ...」）が claude の CLI フラグとして解釈され、モデルや
    system-prompt を差し替える制御平面バイパスになりうるため（実マネーを扱う系では致命的）。
    `--` 以降は全て位置引数として扱われ、フラグにならない。

    stdin は DEVNULL で閉じる（開けたままだと「no stdin data received in 3s」で毎回3秒無駄）。
    子プロセスは新しいプロセスグループで起動し、タイムアウト時はグループごと kill して claude が
    生む MCP wallet 子プロセスも一緒に落とす（孤児・ゾンビの蓄積を防ぐ）。発話者の本人性は
    env COMPASS_ACTIVE_CHILD で mcp_wallet へ渡す（AI の制御外での越境防止）。stderr も取得して
    resume 失敗シグナルの判別と診断に使う。

    Args:
        prompt: 子どもの発話のみ。system 指示は含めない。
        session_id: 継続する claude セッション。無ければ新規セッション。
        system_prompt: --append-system-prompt で渡す人格・約束事。
        child_name: env COMPASS_ACTIVE_CHILD へ渡す発話者名。

    Returns:
        tuple[int, str, str]: (returncode, stdout テキスト, stderr テキスト)。

    Raises:
        asyncio.TimeoutError: 応答が CLI_TIMEOUT_SEC を超えた場合（プロセスは kill 済み）。
        Exception: subprocess の起動失敗（claude 不在・権限等）。
    """
    # 親モードでは親用 tool を許可し、子モードでは子用 tool を許可する。--allowedTools と後述の env で二重に絞る。
    allowed_tools = ALLOWED_PARENT_TOOLS if parent_mode else ALLOWED_WALLET_TOOLS
    # 発話者が制御できない固定フラグを先に置き、発話は必ず `--` の後の位置引数にする
    args = [
        CLAUDE_BIN, "--print",
        "--output-format", "json",
        "--append-system-prompt", system_prompt,
    ]
    # 査定 F/B の opener 生成は tool を一切呼ばせない（確定済み外部イベントの通知であり、
    # 通常の「確定入金は tool で記録」ルールで record_income して二重加算するのを防ぐ・N-11.14 blocker #2）。
    if not disable_tools:
        args += ["--mcp-config", str(WALLET_MCP_CONFIG), "--allowedTools", ",".join(allowed_tools)]
    else:
        # --mcp-config を外すだけでは、--resume した子 session が元々持つ MCP 設定・許可 tool を引き継ぎ得る（codex 再現）。
        # --strict-mcp-config で --mcp-config 由来以外の MCP を全て無視し、さらに wallet tool を明示的に禁止して二重防御する。
        args += ["--strict-mcp-config", "--disallowedTools", ",".join(ALLOWED_WALLET_TOOLS + ALLOWED_PARENT_TOOLS)]
    # モデル指定は server env のみ由来。空なら渡さず CLI 既定にする（不在モデルで全会話停止を防ぐ）
    if CLAUDE_MODEL:
        args += ["--model", CLAUDE_MODEL]
    # 新規セッションは ID を事前採番する（fail-closed・失敗時に既存ポインタを壊さない・N-11.14 #4）
    if new_session_id:
        args += ["--session-id", new_session_id]
    # 継続セッションがあれば resume する。会話文脈を保つ要
    if session_id:
        args += ["--resume", session_id]
    # opener 生成は子 session から分岐する。post-filter 通過時だけ新 session を採用し、弾いても元 session を汚さない（N-11.14 #3）
    if fork_session:
        args += ["--fork-session"]
    # end-of-options セパレータの後に発話を置く。以降はフラグとして解釈されない
    args += ["--", prompt]
    child_env = dict(os.environ)
    if parent_mode:
        # 親モード: 発話者束縛は使わず(親は全児童の保護者)、PARENT_MODE と ADMIN_OPS を明示的に立てる。
        # 対象児は親が tool 引数で明示し、mcp_wallet が子ディレクトリ実在のみに限定する。
        child_env.pop("COMPASS_ACTIVE_CHILD", None)
        child_env["COMPASS_PARENT_MODE"] = "1"
        child_env["COMPASS_ALLOW_ADMIN_OPS"] = "1"
        # 発話した親の Discord ID を渡す（N-11.17）。確認待ちは親ごとに保持するため、
        # 別プロセスの mcp_wallet からも「誰へ確認を出すか」が分かる必要がある。
        # 親モードでは child_name に session_key（"parent:<id>"）が入る。
        if str(child_name or "").startswith("parent:"):
            child_env["COMPASS_PARENT_DISCORD_ID"] = str(child_name).split(":", 1)[1]
    else:
        # 子モード: 発話者を束縛して渡す。mcp_wallet はこの子だけを操作対象にする
        child_env["COMPASS_ACTIVE_CHILD"] = child_name
        # 親モードのフラグは子会話 spawn へ絶対に継承させない。「設定しない」は「継承しない」ではないため
        # 明示 pop し、ボットプロセス環境に混入しても子会話では無効化する(Python境界の最後の砦を守る)。
        child_env.pop("COMPASS_ALLOW_ADMIN_OPS", None)
        child_env.pop("COMPASS_PARENT_MODE", None)
    # 起動フェーズ: ここで失敗したらプロセスは立っておらず tool は絶対に実行されていない。
    # 専用例外 _ProcessNeverStarted に変換し、呼び出し側が「再入力を促してよい」と確証できるようにする。
    try:
        proc = await asyncio.create_subprocess_exec(
            *args,
            stdin=asyncio.subprocess.DEVNULL,   # stdin を閉じて3秒待ちを避ける
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            env=child_env,
            start_new_session=True,             # 新プロセスグループ。タイムアウト時にグループごと落とす
        )
    except Exception as start_error:
        raise _ProcessNeverStarted(str(start_error)) from start_error
    # ここから先(通信フェーズ)の例外・タイムアウトは、プロセスが立っており tool が実行済みの可能性が
    # あるため _ProcessNeverStarted にしない。TimeoutError はそのまま伝播、その他の通信例外も伝播する。
    try:
        stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=CLI_TIMEOUT_SEC)
    except asyncio.TimeoutError:
        # グループごと kill して claude の MCP 子プロセスも道連れに落とす
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            # 既に終了していれば何もしない
            pass
        await proc.wait()
        raise
    return (
        proc.returncode,
        stdout.decode("utf-8", errors="replace"),
        stderr.decode("utf-8", errors="replace"),
    )


async def _run_claude(prompt: str, session_id: str | None, system_prompt: str, child_name: str,
                      parent_mode: bool = False) -> tuple[bool, str, str | None, bool, bool]:
    """claude を起動する。resume 対象が死んでいた場合に限り、新規セッションで1回だけやり直す。

    再試行は「resume に使った session_id が失効・破損していて、まだ会話が始まっておらず tool が
    1つも実行されていない」ことが stderr の目印（_RESUME_FAILED_SIGNAL）で確認できた場合だけに
    厳しく限定する。タイムアウトや is_error などその他の失敗では**再試行しない**。それらは wallet
    tool が既に実残高を動かした後かもしれず、同じ発話をもう一度流すと operation_key が変わって
    冪等が効かず、支出・入金が二重適用される（実残高の二重課金）ため。

    Args:
        prompt: 子どもの発話。
        session_id: 継続する claude セッション。
        system_prompt: 人格・約束事。
        child_name: 発話者名（env 束縛用）。

    Returns:
        tuple[bool, str, str | None, bool, bool]:
            (成功, 応答文, session_id, タイムアウトしたか, tool未実行が確実か)。
            session_id は失敗時でも取れたものを返す（呼び出し側が捨てず継続に使える）。
            最後の tool_never_ran は「claude を起動できず tool が1つも実行されていないと
            確証できる失敗」だけ True。ここが True のときだけ呼び出し側は「もう一度言って」と
            再入力を促してよい。False（tool 実行後に壊れた可能性が少しでもある失敗）では、
            同じ発話の再入力は operation_key が変わって二重課金を招くため促してはならない。
    """
    # 1回目: 継続を試みる。タイムアウトと起動失敗は区別して診断する
    timed_out = False
    spawn_failed = False  # claude 起動自体に失敗＝プロセスが立たず tool は絶対に走っていない
    stderr = ""
    try:
        returncode, stdout, stderr = await _spawn_claude(prompt, session_id, system_prompt, child_name, parent_mode=parent_mode)
    except _ProcessNeverStarted as e:
        # プロセス起動自体の失敗。tool は絶対に走っていないので再入力を促してよい
        spawn_failed = True
        returncode, stdout = 1, ""
        _diag("ai_conversation_spawn_error", {"child": child_name, "error": f"{type(e).__name__}: {e}"})
    except asyncio.TimeoutError:
        # タイムアウトは tool 実行後かもしれない。再試行せず終端扱いにする（二重課金防止）
        timed_out = True
        returncode, stdout = 1, ""
        _diag("ai_conversation_timeout", {"child": child_name, "had_session": bool(session_id)})
    except Exception as e:
        # プロセスは立った後の通信例外。tool 実行済みの可能性があるため tool_never_ran にしない
        # (spawn_failed=False のまま)。再入力を促さず、残高確認を促す安全側へ倒す。
        returncode, stdout = 1, ""
        _diag("ai_conversation_comm_error", {"child": child_name, "error": f"{type(e).__name__}: {e}"})

    ok, result, new_sid = _parse_output(stdout)
    # 正常な JSON 応答(is_error 偽・result 有)なら returncode に関わらず成功として扱う。
    # wallet tool 実行時は MCP 子プロセスの teardown 等で returncode≠0 になりやすく、returncode で
    # 弾くと「tool が残高を動かした後なのに失敗応答を返す」不一致になる（残高は動いたのに黙殺）。
    if ok:
        if returncode != 0:
            _diag("ai_conversation_nonzero_exit_ok", {"child": child_name, "returncode": returncode})
        return True, result, new_sid, timed_out, False

    # 再試行は「resume 対象が見つからない」失敗に限る。タイムアウト・その他失敗では絶対に再試行しない。
    # このシグナルは会話開始前に出るため、tool は1つも実行されておらず二重課金にならない
    resume_dead = bool(session_id) and (_RESUME_FAILED_SIGNAL in stderr)
    if resume_dead and not timed_out:
        _diag("ai_conversation_resume_failed", {"child": child_name, "dead_session": session_id})
        try:
            returncode2, stdout2, stderr2 = await _spawn_claude(prompt, None, system_prompt, child_name, parent_mode=parent_mode)
        except _ProcessNeverStarted as e:
            # 新規再試行の起動失敗も tool 実行前。プロセスが立たず tool は走っていないので再入力を促してよい
            _diag("ai_conversation_spawn_error", {"child": child_name, "error": f"{type(e).__name__}: {e}", "retry": True})
            return False, "", None, False, True
        except asyncio.TimeoutError:
            # 新規再試行のタイムアウトは tool 実行後の可能性がある。tool_never_ran=False で再入力を促さない
            # (codex 指摘: ここを一律 tool_never_ran=True にすると再試行タイムアウトで二重課金する)
            _diag("ai_conversation_timeout", {"child": child_name, "retry": True})
            return False, "", session_id, True, False
        except Exception as e:
            # 新規再試行の通信例外も tool 実行済みの可能性。tool_never_ran=False
            _diag("ai_conversation_comm_error", {"child": child_name, "error": f"{type(e).__name__}: {e}", "retry": True})
            return False, "", session_id, False, False
        ok2, result2, new_sid2 = _parse_output(stdout2)
        # 再試行も returncode でなく ok（正常な JSON 応答）で判定する
        if ok2:
            if returncode2 != 0:
                _diag("ai_conversation_nonzero_exit_ok", {"child": child_name, "returncode": returncode2, "retry": True})
            return True, result2, new_sid2, False, False
        # 再試行も失敗。新規セッションで claude が起動し tool を実行した可能性があるため、tool未実行と
        # 断定できない（tool_never_ran=False）。取れた session_id は返す（呼び出し側が継続に使える）
        return False, "", new_sid2, False, False

    # 再試行しない失敗。stderr を診断へ残して原因を追えるようにする
    if not ok:
        _diag("ai_conversation_failed", {
            "child": child_name, "returncode": returncode,
            "timed_out": timed_out, "spawn_failed": spawn_failed, "stderr": stderr[:500],
        })
    # tool 実行後に壊れた（is_error・部分出力・非JSON）可能性がある失敗は、起動失敗と確証できた
    # ケース（spawn_failed）を除き tool_never_ran=False にする。timed_out も当然 False 側。
    # 失敗でも取れた session_id は返す。tool が動いたターンの文脈を次へ繋ぐため
    return False, "", new_sid, timed_out, spawn_failed


async def handle_conversation(channel, user_conf: dict, input_text: str) -> str:
    """子どもの発話を AI 主導で処理し、応答を返す。会話継続と会話ログ記録を行う。

    処理の流れ:
      1. その子の会話セッションから claude session_id を引く（無ければ新規）。
      2. 入力を会話ログへ記録する（reply.record_incoming）。
      3. 「考え中」を送って無反応に見せない（reply.send_reply は通さない例外送信）。
      4. claude CLI を起動して応答と新しい session_id を得る（resume 失敗は新規で復帰）。
      5. 成功時は新しい session_id を保存、失敗時は既存 id を保持（文脈を捨てない）。
      6. reply.send_reply で応答を送信し会話ログへ記録する（唯一の出口）。

    Args:
        channel: 送信先の Discord チャンネル。
        user_conf: 対象児童の設定 dict。
        input_text: 子どもの発話本文。

    Returns:
        str: 送信した応答の完全な内容。空応答なら空文字。
    """
    user_name = str(user_conf.get("name", ""))
    # 同じ子のターンを直列化する。連投による session 破損・tool 二重実行を防ぐ。子が違えば並行
    async with _lock_for(user_name):
        return await _handle_conversation_locked(channel, user_conf, input_text, user_name)


async def handle_parent_conversation(channel, parent_id: int, input_text: str, child_names: list[str]) -> str:
    """親の発話を AI 主導で処理する。親用 tool（支給・調整・承認等）を AI が意図判断で呼ぶ。

    子経路との違い: 発話者は親（特定の子でない）。セッションは親IDで管理し、親 system prompt と
    parent_mode=True で spawn する。コーチング・能動ナッジは付けない（親向けでない）。実残高安全は
    mcp_wallet 側（PARENT_MODE・対象児実在・金額検証・冪等）が最終担保する。

    Args:
        channel: 送信先チャンネル。
        parent_id: 発話した親の Discord ID（セッションキーに使う）。
        input_text: 親の発話本文。
        child_names: 登録児童名の一覧（親 prompt に渡す）。

    Returns:
        str: 送信した応答。
    """
    # 親単位でターンを直列化する（同じ親の連投で session 破損・tool 二重実行を防ぐ）
    session_key = f"parent:{parent_id}"
    async with _lock_for(session_key):
        return await _handle_parent_conversation_locked(channel, session_key, input_text, child_names)


async def _handle_parent_conversation_locked(channel, session_key: str, input_text: str, child_names: list[str]) -> str:
    """handle_parent_conversation の本体。親のロック配下で1ターンを処理する。"""
