"""公的な相談窓口の電話番号（定数のみ）。

**2026/08/11 に大幅縮小した。**
以前はここに正規表現で日本語の危険度を判定する機構（898行）があったが、
実測で次のことが分かったため全廃した（docs/設計_安全機能の再設計.md）:

  ・拾えるのは直球だけ。「もう生きてるのがつらい」「学校いきたくない」は素通り
  ・一方で日常語に誤爆する。「ゲームで死にたいくらい負けた」が urgent 判定
  ・語を足せば誤爆が増え、絞れば取りこぼす。同一ファイルで
    「絞る修正」と「広げる修正」が交互に積まれ、収束していなかった
  ・本番の検知9件はすべてテストユーザーで、実児はゼロ。
    Python 単独検知の唯一の実例は誤爆で、AI がそれを打ち消していた

さらに、親が子チャンネルに在室している構成では、
「親には伝えない」「ここだけの話」といった機構が**そもそも成立していなかった**
（子が書いた瞬間に親が読んでいるため、隠す場所が存在しない）。

いまは会話 AI が受け止め、必要なときに `get_hotlines` tool でここの番号を渡す。
**番号だけは定数で持つ。**AI に生成させると誤った番号を子へ渡す恐れがあり、
自殺予防の文脈でそれは最悪の失敗になるため。

公式確認日: 2026-08-10
  ・189（児童相談所虐待対応ダイヤル）= こども家庭庁
  ・0120-0-78310（24時間子供SOSダイヤル）= 文部科学省
  ・0120-99-7777（チャイルドライン）
  ・0120-279-338（よりそいホットライン）
番号や受付時間は変わりうるので、定期的に公式サイトで確認すること。
"""

HOTLINES = {
    # 虐待・親に言えないことを、親を介さず相談できる窓口
    "abuse": [
        "児童相談所 虐待対応ダイヤル 189（いちはやく・24時間・無料）",
        "チャイルドライン 0120-99-7777（18歳まで・毎日16時〜21時・無料）",
        "24時間子供SOSダイヤル 0120-0-78310（24時間・無料）",
    ],
    # 死にたい気持ち・つらさを相談できる窓口
    "self_harm": [
        "チャイルドライン 0120-99-7777（18歳まで・毎日16時〜21時・無料）",
        "よりそいホットライン 0120-279-338（24時間・無料）",
        "24時間子供SOSダイヤル 0120-0-78310（24時間・無料）",
    ],
    # いじめを相談できる窓口
    "bullying": [
        "24時間子供SOSダイヤル 0120-0-78310（24時間・無料）",
        "チャイルドライン 0120-99-7777（18歳まで・毎日16時〜21時・無料）",
    ],
}

EMERGENCY_LINE = "いのちが今あぶないと思ったら、119番（救急）や110番（警察）にかけていいよ。"


def hotlines_for(hotline_key: str | None) -> str:
    """相談窓口の案内文を返す。**緊急通報先を必ず添える。**

    以前は `urgent: bool` で緊急先の有無を切り替えていたが、
    危険度の判定機構を廃止した今、**誰が urgent を決めるのかが宙に浮く**。
    AI に決めさせると番号の出し分けを AI が握ることになるため、常に添える形にした
    （docs/設計_安全機能の再設計.md 2-3-c）。

    Args:
        hotline_key: HOTLINES のキー（abuse / self_harm / bullying）。

    Returns:
        str: 案内文。未知の種別でも、いちばん広く使える窓口を返す。
    """
    # **無言にしない。**判定機構を廃止した今、kind は AI が決める。
    # 未知の値や空が来ても、いちばん広く使える窓口を返す（黙るのが最悪）。
    lines = HOTLINES.get(hotline_key) or HOTLINES.get("bullying") or []
    if not lines:
        return EMERGENCY_LINE
    body = "\n".join(f"・{x}" for x in lines)
    return f"{body}\n{EMERGENCY_LINE}"
